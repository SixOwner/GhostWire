/// De-cloaks encrypted parameters into memory on demand with zero disk persistence.
fn decloak_bytes(encrypted: &[u8]) -> String {
    let mut decrypted = Vec::with_capacity(encrypted.len());
    let mask_len = OBFUSCATION_MASK.len();

    for (i, &byte) in encrypted.iter().enumerate() {
        let mask = OBFUSCATION_MASK[i % mask_len];
        decrypted.push(byte ^ mask);
    }

    String::from_utf8(decrypted).unwrap_or_default()
}

